/** Select a deterministic placeholder sequence, avoiding adjacent duplicates. */
export function getPlaceholderWords(count: number, seed: string): string[] {
  const rng = createRng(seed);
  const words: string[] = [];
  while (words.length < count) {
    const candidate = rng.pick(PLACEHOLDER_FINANCE_WORDS);
    if (candidate !== words.at(-1)) words.push(candidate);
  }
  return words;
}
